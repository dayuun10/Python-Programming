# 연산자

# 산술 연산자
a = 10
b = 3

print(a + b)        # 덧셈
print(a - b)        # 뺄셈
print(a * b)        # 곱셈
print(a / b)        # 나눗셈(실수)
print(a // b)       # 나눗셈(정수)
print(a % b)        # 나머지
print(a ** b)       # 제곱 

# 복합 대입 연산지
a = 0
a += 4
print(a)            # 4

a -= 2
print(a)            # 2
